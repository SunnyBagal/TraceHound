// Writes src/logos.generated.ts: which of assets/{greptile,coderabbit,tracehound}.png exist.
// Drop official logos into assets/ and re-render; a missing file falls back to the text label.
import { existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ids = ["greptile", "coderabbit", "tracehound"];
const found = Object.fromEntries(ids.map((id) => [id, existsSync(join(root, "assets", `${id}.png`)) ? `${id}.png` : null]));
writeFileSync(
  join(root, "src", "logos.generated.ts"),
  `// Generated by scripts/logos.mjs; do not edit.\nexport const LOGOS: Record<string, string | null> = ${JSON.stringify(found, null, 2)};\n`,
);
console.log("logos:", JSON.stringify(found));
